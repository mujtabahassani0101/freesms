
CREATE PROCEDURE SP_pass  with encryption  AS
DECLARE @ID BIGINT
DECLARE TESTSTD CURSOR FOR
	SELECT ID
	FROM tstudent
	WHERE pass is null
OPEN TESTSTD
FETCH NEXT FROM TESTSTD INTO
	@ID
WHILE @@FETCH_STATUS = 0
BEGIN
	
	update tstudent set pass= CONVERT(INT ,round(rand()*26570,0)),pass2= CONVERT(INT ,round(rand()*26571,0)) WHERE ID = @ID
	FETCH NEXT FROM TESTSTD INTO
		@ID
END
CLOSE TESTSTD
DEALLOCATE TESTSTD